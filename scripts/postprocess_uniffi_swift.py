"""
Postprocesses UniFFI-generated Swift bindings for ttzip_app_core to enforce:
1. SPDX licensing header.
2. Swift 6 strict concurrency compliance (@unchecked Sendable conformances).
3. Leak prevention via defer { buf.deallocate() } in lifting routines.
4. Crash prevention by replacing throwing deinit invocations.
5. Buffer guard against nil and empty buffers in Data initialization.
"""

import sys


def postprocess(swift_path: str) -> None:
    with open(swift_path, "r", encoding="utf-8") as f:
        content = f.read()

    # 1. Ensure the SPDX header is present
    spdx_header = """// Copyright 2026 Witt Kung and TTZip Contributors
// SPDX-License-Identifier: MIT OR Apache-2.0

"""
    if "SPDX-License-Identifier" in content:
        idx = content.find("// This file was autogenerated")
        if idx != -1:
            content = spdx_header + content[idx:]
        else:
            content = spdx_header + content
    elif "Copyright 2026 Witt Kung" not in content:
        content = spdx_header + content

    # 2. Fix mutable globals for Swift 6 strict concurrency
    content = content.replace("nonisolated(unsafe) ", "")
    content = content.replace("static var vtable:", "nonisolated(unsafe) static var vtable:")
    content = content.replace("fileprivate static var handleMap =", "nonisolated(unsafe) fileprivate static var handleMap =")
    content = content.replace("private var initializationResult:", "private let initializationResult:")

    # 3. UniffiHandleMap Sendable conformance
    content = content.replace(
        "fileprivate class UniffiHandleMap<T> {",
        "fileprivate class UniffiHandleMap<T>: @unchecked Sendable {"
    )

    # 4. AppCoreEngine and pure DTO records Sendable & Identifiable conformance
    # Intra-file declarations allow Swift 6 compiler to perform full static verification without @unchecked
    dto_sendable_extensions = """
// MARK: - Intra-Module Concurrency & Interface Alignments (Auto-Generated Postprocess)
extension UniFfiAppCoreError: Sendable {}
extension UniFfiTransferState: Sendable {}
extension UniFfiDeviceDescriptor: Sendable, Identifiable {}
extension UniFfiFavoriteItem: Sendable, Identifiable {}
extension UniFfiTransferJobInfo: Sendable, Identifiable {}
extension UniFfiWorkspaceSession: Sendable, Identifiable {}
extension UniFfiWorkspaceTab: Sendable, Identifiable {}
extension MtpDownloadOutcome: Sendable {}
extension MtpUploadOutcome: Sendable {}
extension MtpConflictPolicy: Sendable {}
"""
    if "extension AppCoreEngine: @unchecked Sendable" not in content:
        content += "\nextension AppCoreEngine: @unchecked Sendable {}\n"
    if "extension MtpConflictPolicy: Sendable" not in content:
        # Replace existing pure Sendable block if present
        if "// MARK: - Intra-Module Concurrency & Interface Alignments (Auto-Generated Postprocess)" in content:
            idx = content.find("// MARK: - Intra-Module Concurrency & Interface Alignments")
            content = content[:idx] + dto_sendable_extensions.lstrip()
        elif "// MARK: - Intra-Module Concurrency Alignments (Auto-Generated Postprocess)" in content:
            idx = content.find("// MARK: - Intra-Module Concurrency Alignments")
            content = content[:idx] + dto_sendable_extensions.lstrip()
        else:
            content += dto_sendable_extensions

    # 5. Ensure RustBuffer deallocate is inside defer to prevent leak on throw
    old_lift = """    public static func lift(_ buf: RustBuffer) throws -> SwiftType {
        var reader = createReader(data: Data(rustBuffer: buf))
        let value = try read(from: &reader)
        if hasRemaining(reader) {
            throw UniffiInternalError.incompleteData
        }
        buf.deallocate()
        return value
    }"""
    new_lift = """    public static func lift(_ buf: RustBuffer) throws -> SwiftType {
        defer { buf.deallocate() }
        var reader = createReader(data: Data(rustBuffer: buf))
        let value = try read(from: &reader)
        if hasRemaining(reader) {
            throw UniffiInternalError.incompleteData
        }
        return value
    }"""
    content = content.replace(old_lift, new_lift)

    # 6. Ensure deinit calls do not use try! to prevent fatal crashes
    content = content.replace("        try! rustCall { uniffi_", "        _ = try? rustCall { uniffi_")

    # 7. Fix CALL_CANCELLED fatalError to deallocate buffer and throw CancellationError
    call_cancelled_old = """        case CALL_CANCELLED:
            fatalError("Cancellation not supported yet")"""
    call_cancelled_new = """        case CALL_CANCELLED:
            callStatus.errorBuf.deallocate()
            throw CancellationError()"""
    content = content.replace(call_cancelled_old, call_cancelled_new)

    # 8. Guard Data.init(rustBuffer:) against nil or empty buffers
    old_data_init = """fileprivate extension Data {
    init(rustBuffer: RustBuffer) {
        self.init(
            bytesNoCopy: rustBuffer.data!,
            count: Int(rustBuffer.len),
            deallocator: .none
        )
    }
}"""
    new_data_init = """fileprivate extension Data {
    init(rustBuffer: RustBuffer) {
        guard let data = rustBuffer.data, rustBuffer.len > 0 else {
            self.init()
            return
        }
        self.init(
            bytesNoCopy: data,
            count: Int(rustBuffer.len),
            deallocator: .none
        )
    }
}"""
    content = content.replace(old_data_init, new_data_init)

    # 9. Guard RustBuffer.deallocate against double free
    old_dealloc = """    func deallocate() {
        try! rustCall { ffi_ttzip_app_core_rustbuffer_free(self, $0) }
    }"""
    new_dealloc = """    func deallocate() {
        guard self.data != nil && self.capacity > 0 else { return }
        try! rustCall { ffi_ttzip_app_core_rustbuffer_free(self, $0) }
    }"""
    content = content.replace(old_dealloc, new_dealloc)

    with open(swift_path, "w", encoding="utf-8") as f:
        f.write(content)


if __name__ == "__main__":
    if len(sys.argv) > 1:
        postprocess(sys.argv[1])
